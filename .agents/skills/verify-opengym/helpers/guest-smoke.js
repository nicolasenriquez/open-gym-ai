async page => {
  const base = 'http://localhost:8080';
  const stamp = new Date().toISOString().replaceAll(':','-');
  const prefix = `.playwright-cli/opengym-${stamp}`;
  const results = [];
  const errors = [];
  const button = name => page.getByRole('button', {name, exact:true});
  const modal = () => page.locator('#modal-root');
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const proof = async (id, detail) => {
    await page.screenshot({path:`${prefix}-${id}.png`, fullPage:true});
    results.push({id, status:'PASS', detail, snapshot:await page.locator('body').ariaSnapshot()});
  };
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(base);
    const response = await page.request.get(base + '/api/health');
    const health = await response.json();
    assert(response.ok() && health.ok === true, 'Doctor: API unhealthy');
    await button('Continuar sin cuenta').waitFor();
    assert(await page.evaluate(() => !localStorage.getItem('gym_guest') && !localStorage.getItem('gym_state_v1') && !localStorage.getItem('gym_user')), 'Use a fresh isolated browser, not an existing guest/account');
    await proof('G01-login', 'Fresh isolated Spanish login; API ok');
    await button('Continuar sin cuenta').click();
    await button('Crear mi propio plan').waitFor();
    assert(await page.getByText('Aún no hay pesajes. Apunta tu peso para empezar la curva.').isVisible(), 'Missing empty bodyweight state');
    await proof('G02-empty', 'Guest empty home');
    await button('Ejercicios').click();
    const search = page.getByRole('textbox', {name:'Buscar…', exact:true});
    await search.fill('zzzz-e2e-no-match');
    await page.getByRole('status',{name:'0 ejercicios',exact:true}).waitFor();
    await button('sentadilla (squat) cuádriceps · peso corporal Plan').waitFor({state:'hidden'});
    await proof('L01-no-match', 'No matching squat in impossible search');
    await search.fill('squat');
    await button('sentadilla (squat) cuádriceps · peso corporal Plan').click();
    await modal().getByRole('button', {name:'Añadir a mi plan', exact:true}).waitFor();
    await proof('L02-detail', 'Real catalogue exercise detail');
    await page.keyboard.press('Escape');
    await modal().locator('.sheet').waitFor({state:'hidden'});
    await page.getByRole('navigation').getByRole('button',{name:'Plan',exact:true}).click();
    await button('Rutinas').click();
    await button('Nueva rutina').click();
    await page.getByRole('textbox').fill('E2E CLI Routine');
    await button('Añadir ejercicio').click();
    await modal().getByRole('textbox', {name:/Buscar entre/}).fill('squat');
    await modal().getByRole('button', {name:'Añadir «sentadilla (squat)»', exact:true}).click();
    await page.keyboard.press('Escape');
    await button('sentadilla (squat) 3 × 10').waitFor();
    await proof('P01-create', 'Created named routine and added squat through picker');
    await page.reload();
    await button('sentadilla (squat) 3 × 10').waitFor();
    assert(await page.getByRole('textbox').inputValue() === 'E2E CLI Routine', 'Routine name lost');
    await proof('P02-persist', 'Routine survived reload');
    await page.getByRole('navigation').getByRole('button',{name:'Plan',exact:true}).click();
    await button('Horario').click();
    await button('Lunes').click();
    await modal().getByRole('button',{name:'E2E CLI Routine 1 ejercicio',exact:true}).click();
    await modal().getByRole('button',{name:'Listo',exact:true}).click();
    await page.reload();
    assert((await button('Lunes').innerText()).includes('E2E CLI Routine'), 'Schedule lost on reload');
    await proof('P03-schedule', 'Monday assignment persisted');
    // Home's alternate entry avoids depending on the weekday when the proof runs.
    await button('Inicio').click();
    await button('Elegir otro entrenamiento').click();
    await page.getByText('E2E CLI Routine',{exact:true}).click();
    await page.getByRole('checkbox',{name:'Serie 1 hecha',exact:true}).waitFor();
    await proof('W01-start', 'Routine started from Home chooser');
    await button('Minimizar').click();
    await page.getByRole('navigation').getByRole('button',{name:'Seguir',exact:true}).click();
    await page.reload();
    await page.getByRole('checkbox',{name:'Serie 1 hecha',exact:true}).check();
    await page.getByRole('checkbox',{name:'Serie 2 hecha',exact:true}).check();
    await page.getByRole('checkbox',{name:'Serie 3 hecha',exact:true}).check();
    await modal().getByRole('button',{name:'Terminar entrenamiento',exact:true}).click();
    await page.getByRole('heading',{name:'¡Entrenamiento completado!',exact:true}).waitFor();
    await proof('W02-finish', 'Resumed, reloaded, checked all three sets and finished via completion sheet');
    await button('¡Genial!').click();
    await button('Progreso').click();
    await button('Todo 1').click();
    await page.getByRole('heading',{name:'Historial',exact:true}).waitFor();
    await page.reload();
    await page.getByRole('button',{name:/^E2E CLI Routine .*3 series/}).waitFor();
    await proof('H01-history', 'Exactly one finished session visible after reload through Stats > Todo');
    await page.getByRole('button',{name:/^E2E CLI Routine .*3 series/}).click();
    await proof('H02-detail', 'Saved workout opened from history');
    await page.keyboard.press('Escape');
    await page.getByRole('navigation').getByRole('button',{name:'Inicio',exact:true}).click();
    await button('Registrar').click();
    await page.getByRole('textbox',{name:'Peso (kg)',exact:true}).fill('72.5');
    await modal().getByRole('button',{name:'Guardar',exact:true}).click();
    await page.reload();
    await page.locator('body').filter({hasText:'72,5'}).waitFor();
    assert((await page.locator('body').innerText()).includes('72,5'), 'Weight lost');
    await proof('B01-weight', 'Fictitious 72.5 kg saved and reloaded');
    await button('Progreso').click();
    await page.locator('.card').filter({has:page.getByRole('heading',{name:'Medidas corporales',exact:true})}).getByRole('button',{name:'Abrir',exact:true}).click();
    await button('Registrar').click();
    await modal().getByRole('button',{name:'Guardar',exact:true}).click();
    await page.getByText('Introduce al menos una medida',{exact:true}).waitFor();
    await proof('B02-validation', 'Empty measurement rejected');
    await page.getByRole('textbox',{name:'Cintura cm',exact:true}).fill('85');
    await modal().getByRole('button',{name:'Guardar',exact:true}).click();
    await page.reload();
    await page.locator('body').filter({hasText:'85 cm'}).waitFor();
    await proof('B03-measurement', 'Fictitious waist measurement persisted');
    await page.getByRole('navigation').getByRole('button',{name:'Inicio',exact:true}).click();
    await button('Ajustes').click();
    await page.getByRole('textbox',{name:'Buscar en Ajustes',exact:true}).fill('Tema');
    await page.getByText('Tema',{exact:true}).waitFor();
    await proof('S01-search', 'Settings search for Tema');
    await page.goto(base + '/#/settings/look');
    await button('Claro').click();
    await page.reload();
    await page.waitForFunction(()=>document.documentElement.dataset.theme === 'light');
    assert(await page.evaluate(()=>document.documentElement.dataset.theme) === 'light', 'Theme lost');
    await proof('S02-theme', 'Light theme survived reload');
    await page.goto(base + '/#/settings/data');
    const downloadPromise = page.waitForEvent('download');
    await button('Exportar copia (JSON)').click();
    const download = await downloadPromise;
    await download.saveAs(`${prefix}-backup.json`);
    await proof('D01-export', 'JSON downloaded; runner validates exported synthetic data');
    assert(errors.length === 0, 'Unexpected runtime errors: ' + errors.join('; '));
    return {completed:true, prefix, health, results, errors};
  } catch (error) {
    await page.screenshot({path:`${prefix}-FAIL.png`,fullPage:true});
    return {completed:false, prefix, results, errors, failure:String(error), snapshot:await page.locator('body').ariaSnapshot()};
  }
}
